// Draft classes created by the old generator used season-year/stable seeds, so
// new leagues repeatedly loaded the same 2026/2027/etc class. Treat any
// not-started, non-custom draft state without the fresh_random marker as stale
// and force a true regeneration.
function getDraftRowsFromState(state = {}) {
  if (!state || typeof state !== "object") return [];
  if (Array.isArray(state.availableProspects)) return state.availableProspects;
  if (Array.isArray(state.draftClass)) return state.draftClass;
  if (Array.isArray(state.prospects)) return state.prospects;
  if (Array.isArray(state.players)) return state.players;
  if (Array.isArray(state.currentDraftClass?.draftClass)) return state.currentDraftClass.draftClass;
  return [];
}

function isCustomDraftState(state = {}) {
  const classType = String(state?.classType || state?.classMeta?.classType || "").toLowerCase();
  return classType === "custom" || Boolean(state?.customDraftClass || state?.isCustomDraftClass);
}

function isFreshRandomDraftState(state = {}) {
  const seedMode = String(state?.seedMode || state?.classMeta?.seedMode || "").toLowerCase();
  return seedMode === "fresh_random";
}

function isLegacyAutoGeneratedDraftState(state = {}, seasonYear = 2026) {
  if (!state || typeof state !== "object") return false;
  if (Number(state.seasonYear || seasonYear) !== Number(seasonYear)) return false;
  if (isCustomDraftState(state)) return false;
  if (isFreshRandomDraftState(state)) return false;

  const draftedCount = Array.isArray(state.draftedPicks) ? state.draftedPicks.length : 0;
  if (state.completed || draftedCount > 0) return false;

  const rows = getDraftRowsFromState(state);
  if (!rows.length) return false;

  // Old saved auto classes either explicitly report seedMode="provided" or do
  // not report a seedMode at all. Both should be regenerated before the draft starts.
  return true;
}

function clearSavedLegacyDraftState(seasonYear, reason = "legacy auto draft state") {
  const saved = safeJSON(localStorage.getItem(DRAFT_STATE_KEY), null);
  if (isLegacyAutoGeneratedDraftState(saved, seasonYear)) {
    console.warn(`[Draft] Clearing ${reason} from ${DRAFT_STATE_KEY}`, {
      seasonYear,
      seed: saved?.seed || saved?.classMeta?.seed || null,
      seedMode: saved?.seedMode || saved?.classMeta?.seedMode || null,
      classType: saved?.classType || saved?.classMeta?.classType || null,
      topProspect: getDraftRowsFromState(saved)?.[0]?.name || null,
    });
    localStorage.removeItem(DRAFT_STATE_KEY);
    return true;
  }
  return false;
}

function stripLegacyDraftStateFromLeagueData(leagueData, seasonYear) {
  if (!leagueData || typeof leagueData !== "object") return leagueData;

  const staleDraftState = isLegacyAutoGeneratedDraftState(leagueData.draftState, seasonYear);
  const staleCurrentClass = isLegacyAutoGeneratedDraftState(leagueData.currentDraftClass, seasonYear);
  const staleDraftClass = isLegacyAutoGeneratedDraftState({
    seasonYear,
    draftClass: Array.isArray(leagueData.draftClass) ? leagueData.draftClass : [],
  }, seasonYear);
  const staleProspects = isLegacyAutoGeneratedDraftState({
    seasonYear,
    prospects: Array.isArray(leagueData.prospects) ? leagueData.prospects : [],
  }, seasonYear);

  if (!staleDraftState && !staleCurrentClass && !staleDraftClass && !staleProspects) {
    return leagueData;
  }

  const next = { ...leagueData };
  const preservedDraftOrder = Array.isArray(leagueData.draftState?.draftOrder)
    ? leagueData.draftState.draftOrder
    : [];

  if (preservedDraftOrder.length) {
    next.draftState = {
      seasonYear: Number(seasonYear),
      draftOrder: preservedDraftOrder,
      staleAutoClassCleared: true,
    };
  } else {
    delete next.draftState;
  }

  delete next.currentDraftClass;
  delete next.draftClass;
  delete next.prospects;

  return next;
}

  function safeJSON(raw, fallback = null) {
    try {
      const parsed = JSON.parse(raw);
      return parsed ?? fallback;
    } catch {
      return fallback;
    }
  }

  function getSeasonYear(leagueData) {
    const candidates = [];

    const pushYear = (value) => {
      const y = Number(value);
      if (Number.isFinite(y) && y >= 2020 && y <= 2100) {
        candidates.push(y);
      }
    };

    const meta = safeJSON(localStorage.getItem("bm_league_meta_v1"), {}) || {};
    const offseasonState = safeJSON(localStorage.getItem(OFFSEASON_STATE_KEY), {}) || {};

    pushYear(offseasonState?.draftYear);
    pushYear(leagueData?.draftYear);
    pushYear(leagueData?.currentDraftYear);
    pushYear(leagueData?.draftState?.seasonYear);
    pushYear(meta?.draftYear);
    pushYear(getDraftYear(leagueData || {}));
    pushYear(offseasonState?.seasonYear);

    if (candidates.length) return Math.max(...candidates);
    return 2026;
  }

