  function readDraftClassModeForYear(seasonYear, hasCustomClass = false) {
    const yearKey = String(Number(seasonYear || 2026));
    const modesByYear = safeJSON(localStorage.getItem(CUSTOM_DRAFT_CLASS_MODE_BY_YEAR_KEY), null) || {};
    const explicitYearMode = modesByYear?.[yearKey];

    if (explicitYearMode === "custom" || explicitYearMode === "auto") {
      return explicitYearMode;
    }

    const legacyModeConfig = safeJSON(localStorage.getItem(CUSTOM_DRAFT_CLASS_MODE_KEY), null) || {};
    if (legacyModeConfig.mode === "custom") return "custom";
    if (legacyModeConfig.mode === "auto") return "auto";

    // If a class exists but no explicit choice exists yet, use it.
    // Play.jsx writes an explicit auto/custom value, so users can still override per year.
    return hasCustomClass ? "custom" : "auto";
  }

  function readCustomDraftClassSetup(seasonYear) {
    const savedSeasonClass = readCustomDraftClassForYear(seasonYear);
    const savedDefaultClass = readDefaultCustomDraftClass();
    const draftClassPayload = savedSeasonClass || savedDefaultClass || null;
    const rows = getRowsFromDraftClassPayload(draftClassPayload);
    const hasCustomClass = rows.length > 0;
    const mode = readDraftClassModeForYear(seasonYear, hasCustomClass);

    if (mode !== "custom") {
      return { mode, draftClassPayload: null, hasCustomClass };
    }

    if (!draftClassPayload || typeof draftClassPayload !== "object" || !hasCustomClass) {
      return { mode, draftClassPayload: null, hasCustomClass: false };
    }

    const classSeasonYear = Number(draftClassPayload.seasonYear || draftClassPayload.draftClassYear || rows?.[0]?.draftClassYear || rows?.[0]?.seasonYear || seasonYear);
    if (classSeasonYear && Number(classSeasonYear) !== Number(seasonYear)) {
      return { mode, draftClassPayload: null, hasCustomClass: false };
    }

    return {
      mode,
      hasCustomClass: true,
      draftClassPayload: {
        ...draftClassPayload,
        seasonYear: Number(seasonYear),
        draftClass: rows.map((row, index) => ({
          ...row,
          draftClassYear: Number(row?.draftClassYear || row?.seasonYear || seasonYear),
          seasonYear: Number(row?.seasonYear || row?.draftClassYear || seasonYear),
          draftProjection: Number(row?.draftProjection || row?.trueRank || row?.rank || index + 1),
          trueRank: Number(row?.trueRank || row?.draftProjection || row?.rank || index + 1),
        })),
      },
    };
  }

  function getMatchingUpcomingDraftPreview(seasonYear, customSetup) {
    const preview = readUpcomingDraftClassForYear(seasonYear);
    if (!preview?.draftClass?.length) return null;

    if (customSetup?.mode === "custom") {
      const customRows = customSetup?.draftClassPayload?.draftClass || [];
      const customFingerprint = getDraftClassFingerprint(customRows);
      if (
        preview.sourceMode === "custom" &&
        preview.sourceFingerprint &&
        preview.sourceFingerprint === customFingerprint
      ) {
        return preview;
      }
      return null;
    }

    return preview.sourceMode === "auto" ? preview : null;
  }

  function applyDraftClassSourceMetadata(result, descriptor, seasonYear) {
    if (!result?.ok || !descriptor) return result;

    const sourceMode = descriptor.sourceMode === "custom" ? "custom" : "auto";
    const classType =
      sourceMode === "custom"
        ? "custom"
        : descriptor.classType || descriptor.classMeta?.classType || "auto";
    const seedMode = sourceMode === "custom" ? "custom" : "fresh_random";
    const classMeta = {
      ...(descriptor.classMeta || {}),
      seasonYear: Number(seasonYear),
      classType,
      seedMode,
      sourceMode,
      previewGenerated: Boolean(descriptor.previewGenerated || descriptor.sourceMode === "auto"),
    };

    const nextState = result?.draftState
      ? {
          ...result.draftState,
          seasonYear: Number(seasonYear),
          classType,
          seedMode,
          classMeta,
          customDraftClass: sourceMode === "custom",
          isCustomDraftClass: sourceMode === "custom",
        }
      : result?.draftState;

    if (!result?.leagueData || !nextState) {
      return { ...result, draftState: nextState };
    }

    const rootDraftState =
      result.leagueData.draftState && typeof result.leagueData.draftState === "object"
        ? result.leagueData.draftState
        : {};

    return {
      ...result,
      draftState: nextState,
      leagueData: {
        ...result.leagueData,
        draftState: {
          ...rootDraftState,
          seasonYear: Number(seasonYear),
          draftClass: nextState.draftClass || rootDraftState.draftClass || [],
          classType,
          seedMode,
          classMeta,
          draft: nextState,
        },
      },
    };
  }

  function getDraftOrderSignature(order = []) {
    if (!Array.isArray(order) || !order.length) return "";
    return order
      .map((pick, index) => {
        const number = Number(pick?.pick || index + 1);
        const owner = pick?.currentOwnerTeamName || pick?.teamName || "";
        const original = pick?.originalTeamName || pick?.originalOwnerTeamName || "";
        return `${number}:${owner}:${original}`;
      })
      .join("|");
  }

