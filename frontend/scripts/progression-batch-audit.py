    args = ap.parse_args()

    if args.sims > 1:
        # Automatically run each simulation in a fresh Python process, then merge
        # the CSVs. This keeps the command simple for VS terminal while avoiding
        # cached hidden-career state leaking between universes.
        return run_multi_sim_isolated(args)

