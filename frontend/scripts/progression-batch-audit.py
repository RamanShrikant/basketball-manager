def run_multi_sim_isolated(args: argparse.Namespace) -> int:
    """Run each sim in a fresh Python process, then merge CSV outputs.

    The progression modules keep a lot of deterministic career/profile cache state.
    A fresh process per sim is safer for 10x/20x audit runs and prevents one long
    Python process from carrying stale state across unrelated universes.
    """
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    per_sim_root = out / "_per_sim"
    if per_sim_root.exists():
        shutil.rmtree(per_sim_root)
    per_sim_root.mkdir(parents=True, exist_ok=True)

    for sim in range(1, args.sims + 1):
        sim_out = per_sim_root / f"sim{sim:02d}"
        sim_seed = int(args.seed) + sim * 100000
        cmd = [
            sys.executable,
            str(Path(__file__).resolve()),
            "--roster", str(args.roster),
            "--years", str(args.years),
            "--sims", "1",
            "--sim-index", str(sim),
            "--seed", str(sim_seed),
            "--output", str(sim_out),
            "--retirements", str(args.retirements),
        ]
        if args.custom_draft:
            cmd.extend(["--custom-draft", str(args.custom_draft)])
        subprocess.run(cmd, check=True)
        print(f"isolated sim {sim}/{args.sims} merged source ready", flush=True)

    (out / "AUDIT_VERSION.txt").write_text(AUDIT_VERSION + "\n", encoding="utf-8")
    for filename in CSV_OUTPUT_FILES:
        target = out / filename
        wrote_header = False
        with target.open("w", newline="", encoding="utf-8") as fout:
            writer = None
            for sim_dir in sorted(per_sim_root.glob("sim*")):
                src = sim_dir / filename
                if not src.exists():
                    continue
                with src.open("r", newline="", encoding="utf-8") as fin:
                    reader = csv.reader(fin)
                    try:
                        header = next(reader)
                    except StopIteration:
                        continue
                    if not wrote_header:
                        writer = csv.writer(fout)
                        writer.writerow(header)
                        wrote_header = True
                    if writer is None:
                        continue
                    for row in reader:
                        writer.writerow(row)
    print(f"wrote merged isolated audit files to {out}", flush=True)
    return 0


