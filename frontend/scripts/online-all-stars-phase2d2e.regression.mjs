import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {firstBlockedOnlineCheckpoint,isOnlineAllStarSelected} from '../src/online/onlineSimulationCheckpoints.mjs';
const read=file=>readFileSync(new URL(file,import.meta.url),'utf8');
const schedule=read('../src/online/OnlineSeasonSchedule.jsx');
const card=read('../src/online/OnlineAllStarCheckpoint.jsx');
const backend=read('../../backend/onlineAllStars.js');
assert.match(schedule,/OnlineAllStarCheckpoint/);
assert.match(card,/AllStarsContent/);
assert.match(card,/\/api\/online\/calendar\/select-all-stars/);
assert.match(card,/isOnlineAllStarSelected/);
assert.doesNotMatch(card,/localStorage|setLeagueData|singlePlayer/);
assert.match(backend,/runOriginalAllStarSelector/);
assert.match(backend,/expectedRevision/);
assert.match(backend,/bm_online_select_all_stars_phase2d2e/);
const s={seasonStartYear:2026,onlineSchedule:{phase:'regular-season',seasonYear:2026,byDate:{'2027-02-22':[{id:'a',home:'A',away:'B'}]}},onlineResults:{},onlineCheckpoints:{trade_deadline:{status:'closed',seasonYear:2026,date:'2027-02-04',revision:3}}};
assert.equal(firstBlockedOnlineCheckpoint(s,'2027-02-22')?.kind,'all_star');
s.onlineCheckpoints.all_star={status:'selected',seasonYear:2026,date:'2027-02-21',revision:4};
s.onlineAllStars={season:'2026-2027',cutoff_date:'2027-02-21',east:{starters:[1,2,3,4,5],reserves:[1,2,3,4,5,6,7]},west:{starters:[1,2,3,4,5],reserves:[1,2,3,4,5,6,7]}};
assert.equal(isOnlineAllStarSelected(s,'2027-02-21'),true);
assert.equal(firstBlockedOnlineCheckpoint(s,'2027-02-22'),null);
assert.equal(firstBlockedOnlineCheckpoint(s,'2027-04-01')?.kind,'extension_deadline');
console.log('Online All-Star checkpoint, parity presentation and extension guard passed.');
