import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base = new URL('../src/',import.meta.url);
const source=readFileSync(new URL('pages/TeamHub.jsx',base),'utf8');
const mirror=readFileSync(new URL('online/OnlineTeamHubMirror.jsx',base),'utf8');
const app=readFileSync(new URL('online/OnlineApp.jsx',base),'utf8');
const franchise=readFileSync(new URL('online/OnlineFranchise.jsx',base),'utf8');
const sidebar=readFileSync(new URL('online/OnlineBmSidebar.jsx',base),'utf8');
const context=readFileSync(new URL('online/onlineReadOnlyContext.jsx',base),'utf8');
const css=readFileSync(new URL('online/online.css',base),'utf8');
assert(mirror.includes('className={styles.dashboard}'),'reuses the actual single-player Team Hub JSX');
assert(mirror.includes('from "../components/TeamHub.module.css"'),'reuses original Team Hub CSS module');
assert(!/\b(localStorage|sessionStorage)\s*\./.test(mirror),'no direct browser storage reads in mirror');
assert(!mirror.includes('from "../context/GameContext"'),'mirror does not import single-player GameContext');
assert(!mirror.includes('generateFullSeasonSchedule('),'mirror cannot create single-player calendar');
assert(!mirror.includes('persistScheduleStructure('),'mirror cannot write single-player calendar');
assert(!mirror.includes('saveLeagueDataInBackground('),'mirror cannot write single-player league');
assert(!mirror.includes('PlayerCardModal'),'mirror avoids single-player modal storage reads');
assert(context.includes('const OnlineReadOnlyContext = createContext(null)'),'separate provider');
assert(!context.includes('GameProvider') || context.includes('does not mount GameProvider'),'provider is not instantiated');
assert(sidebar.includes('TeamHubSidebar.module.css'),'same original sidebar styling');
assert(sidebar.includes('OnlineBmIcons.jsx'),'same sidebar SVG icons');
assert(sidebar.includes('encodeURIComponent(path)'),'sidebar navigation stays online');
assert(franchise.includes('<OnlineTeamHubMirror/>'),'uses actual TeamHub mirror');
assert(franchise.includes('readOnlineRuntime(id)') && franchise.includes('initializeOnlineRuntime(id)'),'Supabase runtime remains the source of truth');
assert(franchise.includes('OnlineGmPanel'),'player panel present');
assert(app.includes('on-root-franchise'),'franchise full screen');
assert(css.includes('Phase 2B UI: same single-player Team Hub dashboard'),'Online-only CSS present');
console.log('PASS: Team Hub JSX mirrored; single-player provider and browser save reads isolated; Online navigation and GM drawer guarded');
