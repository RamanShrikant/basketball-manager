assert(css.includes('.on-existing-lobby'),'Resume card styling installed');
assert(/\.on-primary\s*\{[^}]*background:/m.test(css),'Online primary button retains defined background styling');
assert(/\.on-primary:not\(:disabled\):hover/.test(css),'Online primary hover feedback remains available');
assert(css.includes('.on-existing-lobby'),'Online existing-lobby card remains styled');
assert(!/from\s*[\"'][^\"']*GameContext/.test(home) && !/from\s*[\"'][^\"']*GameContext/.test(api),'Online is isolated from single-player context');
