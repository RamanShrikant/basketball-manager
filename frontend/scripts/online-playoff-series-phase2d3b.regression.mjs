import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {findPendingOnlinePlayoffGame,onlineSeriesPlayedGames,onlinePlayoffCompletion} from '../src/online/onlinePlayoffReadModel.mjs';
const read=path=>readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const page=read('src/online/OnlinePlayoffPicturePreview.jsx');
