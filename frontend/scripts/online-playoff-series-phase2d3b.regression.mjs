assert.equal(onlineSeriesPlayedGames(series,{g1:{box:{}},g2:{box:{}}}).length,2);
assert.equal(onlinePlayoffCompletion(post).active,1);
assert.equal(findPendingOnlinePlayoffGame({...post,phase:'postseasonComplete'}),null);
assert.match(app,/api\/online\/postseason\/simulate-playoff/);
assert.match(server,/authorize\(req,'playoff_game_simulated'\)/);
assert.match(server,/integrateOnlinePlayoffGame\(/);
assert.match(sql,/for update/i);
assert.match(sql,/v_post is distinct from p_postseason/i);
assert.match(sql,/to service_role/i);
assert.match(page,/Simulate next playoff game/);
assert.match(page,/NBA CHAMPIONS/);
assert.match(page,/onBox\(g\.id\)/);
assert.match(page,/onlinePostseasonRequestId\(lobbyId,operation\)/);
