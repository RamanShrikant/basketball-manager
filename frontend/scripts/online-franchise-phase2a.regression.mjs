import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read = p => readFileSync(new URL('../'+p,import.meta.url),'utf8');
const app=read('src/online/OnlineApp.jsx');
const home=read('src/online/OnlineHome.jsx');
const lobby=read('src/online/OnlineLobby.jsx');
const franchise=read('src/online/OnlineFranchise.jsx');
const api=read('src/online/onlineFranchiseApi.js');
const sql=readFileSync(new URL('../../supabase/bm_online_franchise_phase2a.sql',import.meta.url),'utf8');
assert(app.includes('path="/online/franchise/:id"'),'read-only franchise route is registered');
assert(home.includes('Continue Shared League →') || (home.includes('View My Leagues →') && app.includes('path="/online/library"')),'shared franchise continuation must be accessible via Online Home or Library');
assert(lobby.includes('launchSharedFranchise(lobby)'),'host can launch Online franchise');
assert(lobby.includes('!isHost||!allReady'),'Start League guarded to host and all-ready lobby');
assert(lobby.includes('lobby?.status==="started"'),'joined members follow started lobby');
assert(lobby.includes('bm_set_online_team')&&lobby.includes('bm_set_online_ready'),'team and ready RPCs preserved');
assert(franchise.includes('franchiseForLobby(id)'),'viewer loads authoritative Supabase snapshot');
assert(!franchise.includes('setInterval('),'do not repeatedly download full immutable roster');
assert(franchise.includes('room?.members?.find'),'viewer scopes to signed-in human GM');
assert(!/from\s+[\"'][^\"']*(GameContext|GameProvider|saveLeagueData|accountLocalVault|cloudSaveClient|simEnginePy)/.test(franchise+api),'no single-player runtime imports');
assert(sql.includes('for update'),'lobby launched under transactional row lock');
assert(sql.includes("v_count<2 or v_count>4 or v_count<>v_assigned"),'requires 2–4 all-ready players');
assert(sql.includes("v_lobby.host_id<>auth.uid()"),'host-only launch');
assert(sql.includes('enable row level security'),'RLS exists');
assert(sql.includes('revoke all on public.bm_online_franchises'),'read only by design');
assert(!/\b(insert|update|delete)\s+on\s+public\.bm_online_franchises\s+to\s+authenticated/i.test(sql),'no writes granted to clients');
assert(sql.includes('seed_state jsonb not null'),'immutable full JSON seed');
assert(sql.includes("status in ('waiting','closed','started')"),'started status schema migration');
assert(sql.includes('grant execute on function public.bm_launch_online_franchise'),'authenticated RPC');
// Exercise the pure seed-size/team-match validation without network or browser.
const source=api.replace(/^import .*;\s*$/gm,'').replace(/^export /gm,'')
  +'\n;globalThis.__validation={validateSeed,teamsInSnapshot};';
const sandbox={TextEncoder,JSON,Array,Error};sandbox.globalThis=sandbox;
vm.runInNewContext(source,sandbox);
const {validateSeed,teamsInSnapshot}=sandbox.__validation;
sandbox.extractTeams=snapshot=>teamsInSnapshot(snapshot).map(team=>team?.name);
const snap={teams:[{name:'Boston Celtics',players:[{name:'Player A',overall:84}]},{name:'Toronto Raptors',players:[{name:'Player B',overall:76}]}]};
assert.equal(validateSeed(snap,['Boston Celtics','Toronto Raptors']),snap);
assert.throws(()=>validateSeed(snap,['Toronto Raptors','Chicago Bulls']),/does not match/);
assert.equal(teamsInSnapshot({conferences:{East:[{name:'A'}],West:[{name:'B'}]}}).length,2);
console.log('PASS: Phase 2A host-only transactional launch, read-only shared franchise, team integrity and Online isolation');
